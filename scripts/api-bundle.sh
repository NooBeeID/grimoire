#!/usr/bin/env bash
# Bundle api/root.yml (+ api/modules/**) menjadi satu file OpenAPI.
# Pakai: scripts/api-bundle.sh <output>
set -euo pipefail
cd "$(dirname "$0")/.."

# Versi dipin eksak di satu tempat ini (rules.txt 15.4).
REDOCLY_VERSION="${REDOCLY_VERSION:-1.34.5}"

out="${1:?usage: api-bundle.sh <output>}"
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
tmp="$tmpdir/bundle.yml" # redocly mensyaratkan ekstensi .yml/.yaml

npx --yes "@redocly/cli@${REDOCLY_VERSION}" bundle api/root.yml -o "$tmp"
{
  printf '%s\n' '# GENERATED by scripts/api-bundle.sh from api/root.yml + api/modules/**. DO NOT EDIT. Run: make api-bundle'
  cat "$tmp"
} > "$out"
